#!/usr/bin/env python3
"""Generate src/port/globals.c: definitions for globals the PS1 build placed by linker-script address
(configs/USA/sym.*.txt). The type comes from the `extern` declaration in the game headers.
Usage: gen_globals.py < list-of-undefined-symbol-names"""
import re, sys, glob, pathlib
names = [l.strip() for l in sys.stdin if l.strip()]
hdrs = glob.glob('include/**/*.h', recursive=True) + glob.glob('src/main/*.h') + glob.glob('src/gameplay/*.h')
decl = {}
pat = re.compile(r'^\s*extern\s+([^;()=]*?[\s*])(\w+)((?:\s*\[[^\]]*\])*)\s*;', re.M)
for h in sorted(hdrs):
    t = pathlib.Path(h).read_text(errors='ignore')
    for m in pat.finditer(t):
        decl.setdefault(m.group(2), (h, m.group(1).strip(), m.group(3)))
out = ['/* Generated by tools/port/gen_globals.py: globals the PS1 build defined by address. */\n',
       '#include "types.h"\n#include "common.h"\n']
incs, defs, missing = [], [], []
# Package-owned exports must resolve to their real definitions, never zero stubs.
package_exports = {'gM4a1PlayerAnimationBank', 'gM4a1RifleModel',
                   'gMp5a5PlayerAnimationBank', 'gMp5a5WeaponModel'}
for n in names:
    if n in package_exports:
        raise SystemExit(f'{n} must be exported by its weapon package, not globals.c')
    if n not in decl:
        missing.append(n); continue
    h, ty, arr = decl[n]
    inc = h.replace('include/', '').replace('src/main/', '').replace('src/gameplay/', 'gameplay/') if h.startswith('include/') else h
    incs.append(h)
    if re.fullmatch(r'\s*\[\s*\]', arr or ''):
        arr = '[0x4000]'
    defs.append(f'{ty} {n}{arr};\n')
seen = []
for h in incs:
    if h not in seen: seen.append(h)
for h in seen:
    if h.startswith('include/'):
        out.append(f'#include "{h[len("include/"):]}"\n')
    else:
        out.append(f'#include "{pathlib.Path(h).name}"\n' if h.startswith('src/main/') else f'#include "{h[4:]}"\n')
out += defs
pathlib.Path('src/port/globals.c').write_text(''.join(out))
print(len(defs), 'defined,', len(missing), 'without a header declaration', file=sys.stderr)

