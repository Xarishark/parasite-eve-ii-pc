#!/usr/bin/env python3
"""Give every overlay object its own names for the globals that several overlays define.

The PS1 loaded overlays one at a time, so unrelated packages export the same names (`gRoomEventMsg`). Linked together
they clash. The survey shows no clashing name is referenced from an object that does not define it, so each object can
use a private name: this writes cmake/overlay_renames.cmake, which compiles each object with `-Dname=PE_<object>_name`
for the clashing names it defines.

    gen_overlay_renames.py LINK_LOG [UNDEFINED_LOG [FLIP_LOG]]
LINK_LOG is the output of the failing link (`duplicate symbol` lines). A clashing name that another object refers to
must stay public in one definition: UNDEFINED_LOG is the link log after a first run, whose undefined names are those
(the first definition, game_overlays before the variants, keeps its name). FLIP_LOG is a later log whose undefined
names had the wrong definition kept: for those the variant keeps it instead. Run it again on the next link until no duplicate is left (a renamed symbol can unmask one hidden behind it).
Objects of src/port (asm_data.c, globals.c) are skipped: those names belong to the generated tables, see regen_stubs.sh.
"""
import collections, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
log = pathlib.Path(sys.argv[1]).read_text().splitlines()
out = ROOT / 'cmake/overlay_renames.cmake'
# These resident tables are read outside the package that defines them. Keep
# the base package public, including when a stale generated global stub exists.
resident_exports = {
    'gM4a1PlayerAnimationBank': 'pe_var_m4a1__m4a1',
    'gM4a1RifleModel': 'pe_var_m4a1__m4a1',
    'gMp5a5PlayerAnimationBank': 'pe_var_mp5a5__mp5a5',
    'gMp5a5WeaponModel': 'pe_var_mp5a5__mp5a5',
}
public, flip = set(resident_exports), set()
for i, a in enumerate(sys.argv[2:4]):
    names = set(re.findall(r'^  "_([^"]+)", referenced from', pathlib.Path(a).read_text(), re.M))
    (public if i == 0 else flip).update(names)

defs = collections.defaultdict(list)           # symbol -> [(target, source)]
sym = None
for line in log:
    m = re.match(r"duplicate symbol '([^']+)' in:", line)
    if m:
        sym = m.group(1)
        continue
    m = re.match(r'\s+\S*CMakeFiles/([^/]+)\.dir/(.+)\.o$', line)
    if m and sym:
        defs[sym].append((m.group(1), m.group(2)))
    elif line.strip() == '' or not line.startswith(' '):
        sym = None

per_object = collections.defaultdict(set)      # (target, source) -> C names
skipped = 0
for s, objs in defs.items():
    if len(objs) < 2 or any(src.startswith('src/port/') for _, src in objs):
        skipped += 1
        continue
    name = s[1:] if s.startswith('_') else s
    keep = sorted(objs, key=lambda o: ((o[0] != 'game_overlays') != (name in flip), o))[0] if name in public else None
    if name in resident_exports:
        keep = next((o for o in objs if o[0] == resident_exports[name]), keep)
    for obj in objs:
        if obj == keep:
            continue
        per_object[obj].add(name)

def tag(target, source):
    t = target if target.startswith('pe_var_') else re.sub(r'^src/|\.c$', '', source)
    return 'PE_' + re.sub(r'\W', '_', t).strip('_') + '_'

lines = ['# Generated by tools/port/gen_overlay_renames.py: private names for globals that several overlays define.',
         '# Only used with PE_ALL_VARIANTS. Regenerate from the link log; do not edit.']
for (target, source), names in sorted(per_object.items()):
    defs_ = ';'.join(f'{n}={tag(target, source)}{n}' for n in sorted(names))
    lines.append(f'pe_rename_object({target} {source} "{defs_}")')
out.write_text('\n'.join(lines) + '\n')
print(f'{len(per_object)} objects, {sum(map(len, per_object.values()))} renames, {skipped} symbols skipped', file=sys.stderr)
